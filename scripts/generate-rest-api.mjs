#!/usr/bin/env node
/**
 * Build REST API Markdown pages from exported JSON.
 *
 * Reads data/<plugin>/rest-api.json and writes one page per route under
 * docs/<plugin>/rest-api/*.md plus sidebars/<plugin>.rest-api.json.
 * Always writes rest-api/errors.md for the plugin error catalog.
 * When rest-api-intro/<plugin>/index.md exists, that file is included above
 * the endpoint list on the index page.
 *
 * Optional examples are read from rest-api-examples/<plugin>/<endpoint-slug>.md
 * and copied onto the matching page. The generator never writes under
 * rest-api-examples/.
 *
 * Wire error codes only: the exporter must not include featureErrorMap or
 * feature-layer codes. Generation fails if featureErrorMap is present or if
 * any errors key does not look like a wire code for fluid-checkout/v1.
 */

import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {formatRestApiExampleLog, loadRestApiExamples} from './rest-api-examples.mjs';
import {readRestApiIntro} from './rest-api-intro.mjs';
import {
  prepareRestApiEndpoints,
  renderRestApiEndpointPage,
  renderRestApiErrorsPage,
  renderRestApiIndex,
  renderRestApiSidebarItems,
  resolveRelatedRestApiErrors,
} from './render-rest-api.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/**
 * @param {object} document
 * @param {string} relativePath
 */
export function assertRestApiDocument(document, relativePath) {
  if (!document || typeof document !== 'object') {
    throw new Error(`${relativePath} must be a JSON object.`);
  }
  if ('featureErrorMap' in document) {
    throw new Error(
      `${relativePath} must not include featureErrorMap. Document REST wire codes only.`,
    );
  }
  if (typeof document.namespace !== 'string' || !document.namespace) {
    throw new Error(`${relativePath} is missing namespace.`);
  }
  if (!document.errors || typeof document.errors !== 'object' || Array.isArray(document.errors)) {
    throw new Error(`${relativePath} is missing an errors object.`);
  }
  if (!Array.isArray(document.resources)) {
    throw new Error(`${relativePath} is missing a resources array.`);
  }

  for (const code of Object.keys(document.errors)) {
    if (document.namespace === 'fluid-checkout/v1' && !code.startsWith('fc_api_')) {
      throw new Error(
        `${relativePath} errors key "${code}" is not a wire code (expected fc_api_* for fluid-checkout/v1).`,
      );
    }
  }
}

/**
 * @param {string} rootDir
 * @param {{id: string, label?: string, routeBasePath?: string, relatedRestApiErrors?: string[]}} plugin
 * @param {object} document
 * @param {{id: string, label?: string, navLabel?: string, routeBasePath?: string, status?: string}[]} [catalogPlugins]
 */
export function writeRestApiDocs(rootDir, plugin, document, catalogPlugins = []) {
  const restApiDir = path.join(rootDir, 'docs', plugin.id, 'rest-api');
  fs.mkdirSync(restApiDir, {recursive: true});

  for (const entry of fs.readdirSync(restApiDir)) {
    if (entry.endsWith('.md') || entry.endsWith('.mdx')) {
      fs.unlinkSync(path.join(restApiDir, entry));
    }
  }

  fs.writeFileSync(
    path.join(restApiDir, 'README.md'),
    [
      '# Generated REST API pages',
      '',
      `This directory is generated by \`scripts/generate-rest-api.mjs\` from \`data/${plugin.id}/rest-api.json\`.`,
      '',
      'One Markdown file is written per route, plus `errors.md`. Do not edit these files by hand.',
      'Update the JSON source, `rest-api-intro/`, or `rest-api-examples/`, then run `npm run generate`.',
      '',
    ].join('\n'),
  );

  const endpoints = prepareRestApiEndpoints(document);
  const examplesDir = path.join(rootDir, 'rest-api-examples', plugin.id);
  const examples = loadRestApiExamples(examplesDir, endpoints, plugin.id);
  const related = resolveRelatedRestApiErrors(plugin, catalogPlugins);

  const intro = readRestApiIntro(plugin.id, rootDir);
  fs.writeFileSync(
    path.join(restApiDir, 'index.md'),
    renderRestApiIndex(document, plugin, intro),
  );
  fs.writeFileSync(
    path.join(restApiDir, 'errors.md'),
    renderRestApiErrorsPage(document, plugin, related),
  );

  for (const endpoint of endpoints) {
    const example = examples.loaded.get(endpoint.slug);
    fs.writeFileSync(
      path.join(restApiDir, `${endpoint.slug}.md`),
      renderRestApiEndpointPage(endpoint, document, plugin, {
        exampleMarkdown: example?.body ?? null,
      }),
    );
  }

  const sidebarPath = path.join(rootDir, 'sidebars', `${plugin.id}.rest-api.json`);
  fs.mkdirSync(path.dirname(sidebarPath), {recursive: true});
  fs.writeFileSync(
    sidebarPath,
    `${JSON.stringify(
      renderRestApiSidebarItems(
        endpoints.map((endpoint) => ({
          slug: endpoint.slug,
          label: endpoint.label,
          resourceId: endpoint.resourceId,
          resourceTitle: endpoint.resourceTitle,
        })),
      ),
      null,
      2,
    )}\n`,
  );

  return {
    endpointCount: endpoints.length,
    examples,
  };
}

function main() {
  const requestedPlugin = process.argv[2];
  const catalog = JSON.parse(fs.readFileSync(path.join(root, 'plugins.json'), 'utf8'));
  const plugins = Array.isArray(catalog.plugins) ? catalog.plugins : [];

  let generatedPlugins = 0;

  for (const plugin of plugins) {
    if (plugin.status !== 'available') {
      continue;
    }
    if (requestedPlugin && plugin.id !== requestedPlugin) {
      continue;
    }

    const dataPath = path.join(root, 'data', plugin.id, 'rest-api.json');
    if (!fs.existsSync(dataPath)) {
      continue;
    }

    const relativePath = path.relative(root, dataPath);
    const document = JSON.parse(fs.readFileSync(dataPath, 'utf8'));
    assertRestApiDocument(document, relativePath);
    const result = writeRestApiDocs(root, plugin, document, plugins);
    generatedPlugins += 1;
    console.log(
      `Generated REST API docs for ${plugin.id} (${result.endpointCount} endpoint page(s)).`,
    );
    for (const line of formatRestApiExampleLog(plugin, result.examples)) {
      console.log(line);
    }
  }

  if (requestedPlugin && generatedPlugins === 0) {
    console.error(`No REST API JSON found for plugin "${requestedPlugin}".`);
    process.exit(1);
  }

  if (generatedPlugins === 0) {
    console.log('No REST API JSON found; skipped REST API generation.');
  }
}

const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  main();
}
